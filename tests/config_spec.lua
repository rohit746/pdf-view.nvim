local eq = require("tests.harness").eq
local config = require("pdf-view.config")

describe("config", function()
  it("starts from the defaults", function()
    local options = config.setup()
    eq(true, options.auto_open)
    eq(true, options.live_reload)
    eq(true, options.hide_cursor)
    eq("mutool", options.mutool)
    eq({ "q" }, options.keymaps.close)
  end)

  it("merges user options over the defaults", function()
    local options = config.setup({ auto_open = false, reload_delay = 50 })
    eq(false, options.auto_open)
    eq(50, options.reload_delay)
    eq(true, options.live_reload)
  end)

  it("replaces a keymap list instead of merging it", function()
    local options = config.setup({ keymaps = { next = { "n" } } })
    eq({ "n" }, options.keymaps.next)
    eq({ "<PageUp>", "<BS>", "<C-b>" }, options.keymaps.prev)
  end)

  it("accepts keymaps = false", function()
    eq(false, config.setup({ keymaps = false }).keymaps)
  end)

  it("accepts a cell_size override", function()
    eq({ 18, 36 }, config.setup({ cell_size = { 18, 36 } }).cell_size)
  end)

  it("does not keep state between setup calls", function()
    config.setup({ auto_open = false })
    eq(true, config.setup().auto_open)
  end)

  local function rejects(opts, pattern)
    local ok, err = pcall(config.setup, opts)
    assert(not ok, "expected setup to fail")
    assert(tostring(err):find(pattern, 1, true), ("error %q should mention %q"):format(tostring(err), pattern))
  end

  it("rejects unknown options", function()
    rejects({ nope = true }, "unknown option `nope`")
  end)

  it("rejects values of the wrong type", function()
    rejects({ auto_open = "yes" }, "`auto_open`")
    rejects({ hide_cursor = 1 }, "`hide_cursor`")
    rejects({ mutool = "" }, "`mutool`")
    rejects({ reload_delay = -1 }, "`reload_delay`")
    rejects({ max_pixels = 1.5 }, "`max_pixels`")
  end)

  it("has zoom defaults and accepts overrides", function()
    local options = config.setup()
    eq({ 1.25, 8, 0.2 }, { options.zoom_step, options.max_zoom, options.pan_step })
    options = config.setup({ zoom_step = 2, max_zoom = 4, pan_step = 1 })
    eq({ 2, 4, 1 }, { options.zoom_step, options.max_zoom, options.pan_step })
  end)

  it("rejects nonsensical zoom settings", function()
    rejects({ zoom_step = 1 }, "`zoom_step`")
    rejects({ zoom_step = "big" }, "`zoom_step`")
    rejects({ max_zoom = 0.5 }, "`max_zoom`")
    rejects({ pan_step = 0 }, "`pan_step`")
    rejects({ pan_step = 1.5 }, "`pan_step`")
  end)

  it("binds the zoom and scroll actions by default", function()
    local keymaps = config.setup().keymaps
    eq({ "+", "=" }, keymaps.zoom_in)
    eq({ "-" }, keymaps.zoom_out)
    eq({ "0" }, keymaps.zoom_reset)
    eq({ "j", "<Down>" }, keymaps.down)
    eq({ "l", "<Right>" }, keymaps.right)
  end)

  it("rejects an unknown transmission mode", function()
    rejects({ transmission = "carrier-pigeon" }, "`transmission`")
  end)

  it("rejects a malformed cell_size", function()
    rejects({ cell_size = { 10 } }, "`cell_size`")
  end)

  it("rejects unknown keymap actions and bad key lists", function()
    rejects({ keymaps = { teleport = { "t" } } }, "unknown keymap action `teleport`")
    rejects({ keymaps = { next = "j" } }, "`keymaps.next`")
  end)
end)

describe("config search and fit options", function()
  local function rejects(opts, pattern)
    local ok, err = pcall(config.setup, opts)
    assert(not ok, "expected setup to fail")
    assert(tostring(err):find(pattern, 1, true), ("error %q should mention %q"):format(tostring(err), pattern))
  end

  it("has defaults for the new options and keys", function()
    local options = config.setup()
    eq(5000, options.search_limit)
    eq({ match = "#ffe14d", current = "#ff8c1a" }, options.highlight)
    eq({ "/" }, options.keymaps.search)
    eq({ "?" }, options.keymaps.search_back)
    eq({ "n" }, options.keymaps.search_next)
    eq({ "N" }, options.keymaps.search_prev)
    eq({ "<Esc>" }, options.keymaps.search_clear)
    eq({ "gO" }, options.keymaps.outline)
    eq({ "w" }, options.keymaps.fit_width)
    eq({ "W" }, options.keymaps.fit_height)
    eq({ "g?" }, options.keymaps.help)
  end)

  it("merges a partial highlight table", function()
    local options = config.setup({ highlight = { current = "#00ff00" } })
    eq({ match = "#ffe14d", current = "#00ff00" }, options.highlight)
  end)

  it("rejects bad search settings", function()
    rejects({ search_limit = 0 }, "`search_limit`")
    rejects({ highlight = "yellow" }, "`highlight`")
    rejects({ highlight = { match = "yellow" } }, "`highlight.match`")
    rejects({ highlight = { match = "#fff" } }, "`highlight.match`")
    rejects({ highlight = { other = "#ffffff" } }, "unknown highlight colour `other`")
  end)
end)
